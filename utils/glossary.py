def render_glossary_expander(terms=None):
    """glossary 중 일부만 골라 expander로 보여준다. terms가 없으면 전체를 보여준다."""
    terms = terms or list(GLOSSARY.keys())
    with st.expander("📖 용어 설명"):
        for t in terms:
            if t in GLOSSARY:
                st.markdown(f"**{t}**: {GLOSSARY[t]}")
